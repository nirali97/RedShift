import sqlite3
from datetime import datetime

DB_PATH = "data/red_shift.db"

def create_tables():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    # 1. Create SCORE_RUN table (Table 8 in your SDS)
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS SCORE_RUN (
        run_id INTEGER PRIMARY KEY AUTOINCREMENT,
        company_id INTEGER NOT NULL,
        fiscal_year INTEGER NOT NULL,
        run_ts TEXT NOT NULL,
        status TEXT(12) NOT NULL,
        m_score REAL,
        z_score REAL,
        f_score INTEGER,
        composite_score REAL,
        severity_band TEXT(12),
        model_version TEXT NOT NULL,
        FOREIGN KEY (company_id) REFERENCES COMPANY(company_id)
    );
    """)

    # 2. Create RED_FLAG table (Table 9 in your SDS)
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS RED_FLAG (
        flag_id INTEGER PRIMARY KEY AUTOINCREMENT,
        run_id INTEGER NOT NULL,
        category TEXT(30) NOT NULL,
        flag_type TEXT(60) NOT NULL,
        severity TEXT(10) NOT NULL,
        explanation TEXT NOT NULL,
        evidence_ref TEXT NOT NULL,
        FOREIGN KEY (run_id) REFERENCES SCORE_RUN(run_id)
    );
    """)

    conn.commit()
    conn.close()
    print("SCORE_RUN and RED_FLAG tables created successfully.")

def save_sample_run():
    """
    Demonstrates saving a completed run and attaching a red flag to it.
    """
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    now_ts = datetime.utcnow().isoformat()

    # Insert a screening run for company_id = 1 (ZEEL)
    cursor.execute("""
    INSERT INTO SCORE_RUN 
    (company_id, fiscal_year, run_ts, status, m_score, z_score, f_score, composite_score, severity_band, model_version)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, (1, 2025, now_ts, "Completed", -1.45, 2.10, 5, 62.5, "High", "v1.0-standard"))

    # Get the run_id generated by the database
    run_id = cursor.lastrowid

    # If M-Score was worse than -1.78, record an incident in RED_FLAG linked to this run_id
    cursor.execute("""
    INSERT INTO RED_FLAG 
    (run_id, category, flag_type, severity, explanation, evidence_ref)
    VALUES (?, ?, ?, ?, ?, ?)
    """, (
        run_id,
        "Quantitative",
        "Beneish M-Score Threshold Breached",
        "High",
        "Beneish M-Score of -1.45 indicates high probability of earnings manipulation.",
        "M-Score = -1.45 > cutoff -1.78; primary driver: elevated receivables (DSRI)"
    ))

    conn.commit()
    conn.close()
    print(f"Logged screening run ID #{run_id} and saved an attached Red Flag!")

if __name__ == "__main__":
    create_tables()
    save_sample_run()